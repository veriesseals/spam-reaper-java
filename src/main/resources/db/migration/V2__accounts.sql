-- V2 — accounts: the users table.
--
-- Backs the accounts module: local email + password login, one role per
-- user. MFA and refresh-token columns are added by a later migration
-- (step 4b), so they are deliberately absent here.

CREATE TABLE users (
                       id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       username   VARCHAR(100) NOT NULL UNIQUE,
                       email      VARCHAR(255) NOT NULL UNIQUE,
                       password   VARCHAR(100) NOT NULL,   -- BCrypt hash (60 chars); headroom to spare
                       role       VARCHAR(40)  NOT NULL,
                       is_active  BOOLEAN      NOT NULL DEFAULT TRUE,
                       created_at TIMESTAMP    NOT NULL,
                       updated_at TIMESTAMP    NOT NULL
);